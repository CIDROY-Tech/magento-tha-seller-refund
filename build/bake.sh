#!/usr/bin/env bash
# Two-pass bake for the assignment images. Run from a machine with Docker.
#
#   build/bake.sh <rN> [--push]
#
# Pass 1 resolves base-image digests, builds the search + stub images and the
# throwaway installer web image, brings up a temporary stack, runs
# bake-inside.sh to install/seed/compile/warm/test, and exports the warmed web
# artefacts plus a DB dump. Pass 2 builds the shippable runtime web image and
# the pre-baked db image, verifies the full stack locally, and (with --push)
# pushes all four images to GHCR and pins their digests into compose.yaml.
#
# Base component versions are the verified, fixed values; do not change them
# here. If a digest has moved, that is recorded in build/base-images.env and
# the build notes - the tags stay the same.
set -euo pipefail
export MSYS_NO_PATHCONV=1

REL=${1:-}
if [ -z "$REL" ]; then
  echo "usage: build/bake.sh <rN> [--push]   (e.g. build/bake.sh r1)" >&2
  exit 2
fi
PUSH=0
if [ "${2:-}" = "--push" ]; then PUSH=1; fi

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO_ROOT=$(cd "$SCRIPT_DIR/.." && pwd)
cd "$REPO_ROOT"

REGISTRY=${REGISTRY:-ghcr.io/cidroy-tech}
WEB_TAG="2.4.7-p10-${REL}"
DB_TAG="2.4.7-p10-${REL}"
SEARCH_TAG="2.12.0-${REL}"
STUB_TAG="1.0.0"

# Fixed base tags (digests resolved below).
PHP_BASE="php:8.3-fpm-bookworm"
COMPOSER_BASE="composer:2.10"
DB_BASE="mariadb:10.11"
SEARCH_BASE="opensearchproject/opensearch:2.12.0"
NODE_BASE="node:20-alpine"

BAKE="docker compose -f build/compose.bake.yaml"

log() { printf '\n[bake] %s\n' "$*"; }

resolve_digest() {
  # Prints the manifest (index) digest for a tag, e.g. sha256:...
  # Prefer the registry (authoritative), but fall back to the locally-pulled
  # image's digest when the registry is unreachable or rate-limited (HTTP 429).
  # All five base images are pulled locally before a bake, so the local digest
  # is the same index digest and the bake needs no Docker Hub round-trip.
  local ref="$1" d=""
  d=$(docker buildx imagetools inspect "$ref" --format '{{.Manifest.Digest}}' 2>/dev/null) || d=""
  if [ -z "$d" ]; then
    d=$(docker inspect "$ref" --format '{{if .RepoDigests}}{{index .RepoDigests 0}}{{end}}' 2>/dev/null | sed -n 's/.*@//p')
    [ -n "$d" ] && echo "[bake]   (using local digest for $ref; registry unavailable)" >&2
  fi
  if [ -z "$d" ]; then
    echo "FATAL: cannot resolve a digest for $ref (registry rate-limited and no local image present; run: docker pull $ref)" >&2
    return 1
  fi
  printf '%s' "$d"
}

# ---------------------------------------------------------------------------
# Pass 1
# ---------------------------------------------------------------------------
log "resolving base-image digests"
PHP_D=$(resolve_digest "$PHP_BASE")
COMPOSER_D=$(resolve_digest "$COMPOSER_BASE")
DB_D=$(resolve_digest "$DB_BASE")
SEARCH_D=$(resolve_digest "$SEARCH_BASE")
NODE_D=$(resolve_digest "$NODE_BASE")

cat > build/base-images.env <<EOF
# Resolved base-image digests for release ${REL} (generated by build/bake.sh).
PHP_BASE_IMAGE=${PHP_BASE}@${PHP_D}
COMPOSER_IMAGE=${COMPOSER_BASE}@${COMPOSER_D}
DB_BASE_IMAGE=${DB_BASE}@${DB_D}
SEARCH_BASE_IMAGE=${SEARCH_BASE}@${SEARCH_D}
NODE_BASE_IMAGE=${NODE_BASE}@${NODE_D}
EOF
log "wrote build/base-images.env"
cat build/base-images.env

log "building search image"
docker build \
  --build-arg "SEARCH_BASE_IMAGE=${SEARCH_BASE}@${SEARCH_D}" \
  -f docker/opensearch/Dockerfile \
  -t seller-refund-search:bake \
  .

log "building erp stub image"
docker build \
  --build-arg "NODE_BASE_IMAGE=${NODE_BASE}@${NODE_D}" \
  -t seller-refund-erp-stub:bake \
  erp-refund-stub

log "building installer web image"
docker build \
  --target installer \
  --build-arg "PHP_BASE_IMAGE=${PHP_BASE}@${PHP_D}" \
  --build-arg "COMPOSER_IMAGE=${COMPOSER_BASE}@${COMPOSER_D}" \
  -f build/Dockerfile \
  -t seller-refund-web:installer \
  .

log "starting temporary bake stack"
SEARCH_IMAGE=seller-refund-search:bake \
STUB_IMAGE=seller-refund-erp-stub:bake \
INSTALLER_IMAGE=seller-refund-web:installer \
DB_BASE_IMAGE="${DB_BASE}@${DB_D}" \
  $BAKE up -d --wait

log "running bake-inside.sh"
$BAKE exec -T -u www-data -e ARTIFACT_OUT=/tmp/web-artifacts.tgz -e "ASSIGNMENT_SEED_VERSION=${REL}" web bash /build/bake-inside.sh

log "exporting warmed web artefacts"
mkdir -p build/artifacts/web build/artifacts/db
$BAKE cp web:/tmp/web-artifacts.tgz build/artifacts/web/web-artifacts.tgz

log "exporting database dump"
$BAKE exec -T db sh -c 'exec mariadb-dump --databases magento --single-transaction --routines --triggers --events -uroot -proot' \
  | gzip > build/artifacts/db/seed.sql.gz

log "tearing down bake stack"
$BAKE down -v

# ---------------------------------------------------------------------------
# Pass 2
# ---------------------------------------------------------------------------
log "building runtime web image"
docker build \
  --target runtime \
  --build-arg "PHP_BASE_IMAGE=${PHP_BASE}@${PHP_D}" \
  --build-arg "COMPOSER_IMAGE=${COMPOSER_BASE}@${COMPOSER_D}" \
  --build-arg "SEED_VERSION=${REL}" \
  -f build/Dockerfile \
  -t seller-refund-web:local \
  .

log "building pre-baked db image"
docker build \
  --build-arg "DB_BASE_IMAGE=${DB_BASE}@${DB_D}" \
  -f docker/database/Dockerfile \
  -t seller-refund-db:local \
  .

docker tag seller-refund-search:bake seller-refund-search:local
docker tag seller-refund-erp-stub:bake seller-refund-erp-stub:local

log "local verification with the shipped compose file"
WEB_IMAGE=seller-refund-web:local \
DB_IMAGE=seller-refund-db:local \
SEARCH_IMAGE=seller-refund-search:local \
STUB_IMAGE=seller-refund-erp-stub:local \
  docker compose -f compose.yaml -f build/compose.local.yaml up -d --wait

log "running assignment-test all against the local stack"
WEB_IMAGE=seller-refund-web:local \
DB_IMAGE=seller-refund-db:local \
SEARCH_IMAGE=seller-refund-search:local \
STUB_IMAGE=seller-refund-erp-stub:local \
  docker compose -f compose.yaml -f build/compose.local.yaml exec -T -u www-data web assignment-test all

log "tearing down local verification stack"
WEB_IMAGE=seller-refund-web:local \
DB_IMAGE=seller-refund-db:local \
SEARCH_IMAGE=seller-refund-search:local \
STUB_IMAGE=seller-refund-erp-stub:local \
  docker compose -f compose.yaml -f build/compose.local.yaml down -v

if [ "$PUSH" -eq 0 ]; then
  log "build complete (local tags only). Re-run with --push to publish to GHCR."
  exit 0
fi

# ---------------------------------------------------------------------------
# Publish
# ---------------------------------------------------------------------------
log "tagging and pushing to ${REGISTRY}"
docker tag seller-refund-web:local    "${REGISTRY}/seller-refund-web:${WEB_TAG}"
docker tag seller-refund-db:local     "${REGISTRY}/seller-refund-db:${DB_TAG}"
docker tag seller-refund-search:local "${REGISTRY}/seller-refund-search:${SEARCH_TAG}"
docker tag seller-refund-erp-stub:local "${REGISTRY}/seller-refund-erp-stub:${STUB_TAG}"

docker push "${REGISTRY}/seller-refund-web:${WEB_TAG}"
docker push "${REGISTRY}/seller-refund-db:${DB_TAG}"
docker push "${REGISTRY}/seller-refund-search:${SEARCH_TAG}"
docker push "${REGISTRY}/seller-refund-erp-stub:${STUB_TAG}"

log "pinning digests into compose.yaml"
REGISTRY="$REGISTRY" build/pin-digests.sh "$REL"

log "bake complete and published for release ${REL}."
